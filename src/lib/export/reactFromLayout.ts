/**
 * reactFromLayout.ts — generate an embeddable React component from a layout
 * (Phase 5, the "ready to embed in a frontend" deliverable).
 *
 * Design choice: this is a *starter* generator, not a framework. It emits one
 * dependency-free `Panel.tsx` that renders the de-haloed background plate plus
 * every asset absolutely-positioned at its exact rect (with rotation). This
 * guarantees pixel-faithful placement (the DoD: "renders assets within a few px
 * of layout.json rects") and makes zero bundler assumptions — assets are loaded
 * by URL from an overridable `assetBase`, so it drops into Vite / CRA / Next
 * without import-plugin config. Claude (or the owner) can refine it from there
 * using layout.json — e.g. swap absolute rects for the semantics flex/grid tree,
 * or wire the interaction presets to Framer Motion.
 *
 * Pure & deterministic (no Date/random) so it is node-testable.
 */

export interface GenElement {
  id: string
  type: string
  /** [x, y, w, h] in panel/original-image pixels. */
  rect: [number, number, number, number]
  /** Rotation in degrees about the element centre. */
  angle?: number
  /** Relative asset path, e.g. 'assets/knob_1.png'. */
  assetFile: string
  /** Human label for alt text; falls back to type. */
  label?: string | null
}

export interface GenScene {
  width: number
  height: number
  /** Relative background path, e.g. 'background/background_filled.png'. */
  backgroundFile?: string | null
  /** Elements in draw order (bottom → top). */
  elements: GenElement[]
  /** Component name; sanitised to a valid identifier. Default 'Panel'. */
  componentName?: string
}

/** Escape a string for use inside a double-quoted JSX/HTML attribute. */
function attr(s: string): string {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

/** Escape a string for a single-quoted JS template-literal segment. */
function tpl(s: string): string {
  return String(s).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

/** Make a safe PascalCase-ish identifier for the component name. */
function safeIdentifier(name: string | undefined, fallback = 'Panel'): string {
  const cleaned = (name ?? '').replace(/[^A-Za-z0-9_$]/g, '')
  if (!cleaned || /^[0-9]/.test(cleaned)) return fallback
  return cleaned
}

function round(n: number): number {
  return Math.round(n)
}

function elementJsx(el: GenElement): string {
  const [x, y, w, h] = el.rect
  const angle = el.angle ?? 0
  const styleParts = [
    `position: 'absolute'`,
    `left: ${round(x)}`,
    `top: ${round(y)}`,
    `width: ${round(w)}`,
    `height: ${round(h)}`,
  ]
  if (angle) {
    styleParts.push(`transform: 'rotate(${angle}deg)'`, `transformOrigin: 'center'`)
  }
  const alt = attr(el.label || el.type || el.id)
  return [
    `      <img`,
    `        src={\`\${assetBase}${tpl(el.assetFile)}\`}`,
    `        alt="${alt}"`,
    `        data-id="${attr(el.id)}"`,
    `        data-type="${attr(el.type)}"`,
    `        draggable={false}`,
    `        style={{ ${styleParts.join(', ')} }}`,
    `      />`,
  ].join('\n')
}

export function generateReactComponent(scene: GenScene): string {
  const name = safeIdentifier(scene.componentName)
  const W = round(scene.width)
  const H = round(scene.height)

  const bgJsx = scene.backgroundFile
    ? [
        `      <img`,
        `        src={\`\${assetBase}${tpl(scene.backgroundFile)}\`}`,
        `        alt=""`,
        `        width={NATURAL_WIDTH}`,
        `        height={NATURAL_HEIGHT}`,
        `        draggable={false}`,
        `        style={{ position: 'absolute', top: 0, left: 0 }}`,
        `      />`,
      ].join('\n')
    : ''

  const elementsJsx = scene.elements.map(elementJsx).join('\n')

  return `// AUTO-GENERATED by SynthSkin Studio — embeddable UI panel.
// Renders the background plate + every asset at its exact rect from layout.json.
// This is a starter: refine freely (semantics tree -> flex/grid, interaction
// presets -> Framer Motion). See README_FOR_CLAUDE.md for the coordinate contract.
import React from 'react'

export interface ${name}Props {
  /** Rendered width in px; the panel scales proportionally. Default = natural width. */
  width?: number
  /** Base path where \`assets/\` and \`background/\` live (must end with '/'). Default './'. */
  assetBase?: string
  className?: string
  style?: React.CSSProperties
}

const NATURAL_WIDTH = ${W}
const NATURAL_HEIGHT = ${H}

export function ${name}({ width = NATURAL_WIDTH, assetBase = './', className, style }: ${name}Props) {
  const scale = width / NATURAL_WIDTH
  return (
    <div
      className={className}
      style={{ position: 'relative', width, height: NATURAL_HEIGHT * scale, overflow: 'hidden', ...style }}
    >
      <div
        style={{
          position: 'absolute',
          top: 0,
          left: 0,
          width: NATURAL_WIDTH,
          height: NATURAL_HEIGHT,
          transform: \`scale(\${scale})\`,
          transformOrigin: 'top left',
        }}
      >
${[bgJsx, elementsJsx].filter(Boolean).join('\n')}
      </div>
    </div>
  )
}

export default ${name}
`
}
