/**
 * handoff.ts — assemble the embeddable "handoff" bundle (Phase 5).
 *
 * Produces the file map for `synthskin-handoff.zip`:
 *   Panel.tsx                 generated React component (see reactFromLayout.ts)
 *   layout.json               enriched manifest (detected + placed/restyled)
 *   assets/<id>.png           per-element transparent crop (de-haloed / baked)
 *   background/*.png          filled + punched plates
 *   preview.png               flat ground-truth render (optional)
 *   README_FOR_CLAUDE.md      the coordinate/interaction contract for refining it
 *
 * Everything here is pure & node-testable; the DOM orchestration (fetching the
 * manifest, baking adjustments, rendering the preview) lives in the modal.
 */
import type { LayoutManifest, LayoutManifestAsset } from '../api/pythonClient'
import type { ComposedLayoutElement } from '../compose/toLayout'
import type { GenElement, GenScene } from './reactFromLayout'
import { createZip, strToU8, base64ToU8, type ZipEntry } from './zip'

export interface HandoffFile {
  path: string
  encoding: 'utf8' | 'base64'
  data: string
}

/** Manifest asset extended with the fields a *placed* element needs. */
export interface HandoffManifestAsset extends LayoutManifestAsset {
  /** Where it came from: an AI-detected control vs. a user-composited part. */
  source?: 'detected' | 'placed'
  /** Static rotation in degrees (placed parts). Distinct from `angle` (knob sweep). */
  rotation?: number
  /** Stacking order (placed parts). */
  z?: number
  /** Non-destructive recolor baked into the crop at export. */
  adjustments?: unknown
}

export interface HandoffManifest extends Omit<LayoutManifest, 'assets'> {
  assets: HandoffManifestAsset[]
  placed_count?: number
}

/** Strip the `data:...;base64,` prefix, returning bare base64. */
export function dataUrlToBase64(dataUrl: string): string {
  const i = dataUrl.indexOf(',')
  return i >= 0 ? dataUrl.slice(i + 1) : dataUrl
}

function placedAsAsset(el: ComposedLayoutElement): HandoffManifestAsset {
  const [x, y, w, h] = el.rect
  return {
    id: el.id,
    type: el.type,
    provenance: 'user',
    source: 'placed',
    rect: el.rect,
    pivot: [x + w / 2, y + h / 2],
    rotation: el.angle || 0,
    z: el.z,
    files: { original: `assets/${el.id}.png` },
    ...(el.adjustments ? { adjustments: el.adjustments } : {}),
  }
}

/**
 * Merge composited/placed elements into a detected-controls manifest. Detected
 * assets are tagged `source:'detected'`; placed ones are appended in z-order.
 */
export function mergePlacedIntoManifest(
  manifest: LayoutManifest,
  placed: ComposedLayoutElement[],
): HandoffManifest {
  const detected: HandoffManifestAsset[] = manifest.assets.map((a) => ({ ...a, source: 'detected' }))
  const placedAssets = [...placed].sort((a, b) => a.z - b.z).map(placedAsAsset)
  const assets = [...detected, ...placedAssets]
  return {
    ...manifest,
    assets,
    asset_count: assets.length,
    placed_count: placedAssets.length,
  }
}

/** Build the generator scene from an (enriched) manifest. */
export function sceneFromManifest(
  manifest: HandoffManifest,
  opts: { backgroundFile?: string | null; componentName?: string } = {},
): GenScene {
  const elements: GenElement[] = manifest.assets.map((a) => {
    const [x, y, w, h] = a.rect
    return {
      id: a.id,
      type: a.type,
      rect: [x, y, w, h],
      angle: a.rotation || 0,
      assetFile: a.files?.original ?? `assets/${a.id}.png`,
      label: a.display_name ?? a.label ?? null,
    }
  })
  return {
    width: manifest.source.width,
    height: manifest.source.height,
    backgroundFile: opts.backgroundFile ?? 'background/background_filled.png',
    elements,
    componentName: opts.componentName ?? 'Panel',
  }
}

